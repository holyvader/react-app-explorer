#!/usr/bin/env bun
/**
 * Builds the desktop app's sidecars into packages/desktop/src-tauri/binaries/:
 *   rae-server-<rust triple>  one executable: the local server + scanner + the built viewer
 *   tsgo/                     TypeScript 7's native binary + lib.*.d.ts (it can't run from inside a Bun executable)
 *
 *   bun run build [--target bun-darwin-arm64|bun-darwin-x64|bun-linux-x64|bun-linux-arm64|bun-windows-x64] [--skip-viewer]
 *
 * Other targets than the host need that platform's native packages installed
 * (@oxc-parser/binding-*, @oxc-resolver/binding-*, @typescript/typescript-*), e.g. with
 * `bun install --os=linux --cpu=x64` on a CI machine for that platform.
 */
import { copyFileSync, chmodSync, existsSync, mkdirSync, readdirSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { parseArgs } from "node:util";

const { values } = parseArgs({ options: { target: { type: "string" }, "skip-viewer": { type: "boolean" } } });

/** Bun compile target → [node platform-arch used by native packages, Rust target triple, exe suffix]. */
const TARGETS: Record<string, [string, string, string]> = {
  "bun-darwin-arm64": ["darwin-arm64", "aarch64-apple-darwin", ""],
  "bun-darwin-x64": ["darwin-x64", "x86_64-apple-darwin", ""],
  "bun-linux-x64": ["linux-x64-gnu", "x86_64-unknown-linux-gnu", ""],
  "bun-linux-arm64": ["linux-arm64-gnu", "aarch64-unknown-linux-gnu", ""],
  "bun-windows-x64": ["win32-x64-msvc", "x86_64-pc-windows-msvc", ".exe"],
};
const hostTarget = `bun-${process.platform === "win32" ? "windows" : process.platform}-${process.arch}`;
const target = values.target ?? hostTarget;
if (!TARGETS[target]) throw new Error(`Unknown target ${target}; one of ${Object.keys(TARGETS).join(", ")}`);
const [platform, triple, exe] = TARGETS[target]!;

const here = import.meta.dir;
const repo = join(here, "../..");
const scanner = join(repo, "packages/scanner");
const viewerDist = join(repo, "packages/viewer/dist");
const outDir = join(repo, "packages/desktop/src-tauri/binaries");
mkdirSync(outDir, { recursive: true });

/** A package's directory as the scanner sees it (Bun's isolated installs keep siblings next to it). */
function pkgDir(from: string, name: string): string {
  const own = join(from, "node_modules", name);
  if (existsSync(own)) return realpathSync(own);
  // a platform package installed next to its parent package in node_modules/.bun/<pkg>/node_modules/
  const parent = realpathSync(join(from, "node_modules", name.startsWith("@oxc-parser") ? "oxc-parser" : name.startsWith("@oxc-resolver") ? "oxc-resolver" : "typescript"));
  const sibling = join(parent, "..", name);
  if (existsSync(sibling)) return realpathSync(sibling);
  throw new Error(`${name} isn't installed — needed for ${target}. Install it for that platform first.`);
}

// 1. the viewer
if (!values["skip-viewer"]) {
  const r = Bun.spawnSync(["bun", "run", "build"], { cwd: join(repo, "packages/viewer"), stdout: "inherit", stderr: "inherit" });
  if (r.exitCode !== 0) throw new Error("viewer build failed");
}
if (!existsSync(join(viewerDist, "index.html"))) throw new Error("packages/viewer/dist is missing: build the viewer first");

// 2. embed it: one `with { type: "file" }` import per file, keyed by its URL path
const files: string[] = [];
const walk = (d: string) => {
  for (const e of readdirSync(d, { withFileTypes: true })) (e.isDirectory() ? walk : (p: string) => files.push(p))(join(d, e.name));
};
walk(viewerDist);
const generated = join(here, "src/embedded.generated.ts");
writeFileSync(
  generated,
  `// Generated by build.ts — the built viewer, embedded into the server executable. Don't edit.\n` +
    files.map((f, i) => `import f${i} from ${JSON.stringify(relative(dirname(generated), f).replaceAll("\\", "/"))} with { type: "file" };`).join("\n") +
    `\n\nexport const assets: Record<string, string> = {\n` +
    files.map((f, i) => `  ${JSON.stringify("/" + relative(viewerDist, f).replaceAll("\\", "/"))}: f${i},`).join("\n") +
    `\n};\n`,
);

// 3. oxc's napi loaders pick a .node file at runtime; rewrite them to one static require of the
//    target's addon so Bun embeds it (and its version check passes).
const parserPkg = pkgDir(scanner, `@oxc-parser/binding-${platform}`);
const resolverPkg = pkgDir(scanner, `@oxc-resolver/binding-${platform}`);
const parserNode = join(parserPkg, `parser.${platform}.node`);
const resolverNode = join(resolverPkg, `resolver.${platform}.node`);
const version = (dir: string) => JSON.parse(require("node:fs").readFileSync(join(dir, "package.json"), "utf8")).version as string;
const rewrite = (src: string, scope: string, node: string, v: string) =>
  src
    .replace(new RegExp(`require\\((['"])${scope}/binding-[a-z0-9-]+/package\\.json\\1\\)\\.version`, "g"), JSON.stringify(v))
    .replace(new RegExp(`require\\((['"])${scope}/binding-[a-z0-9-]+\\1\\)`, "g"), `require(${JSON.stringify(node)})`);
const embedNative: Bun.BunPlugin = {
  name: "embed-oxc-native",
  setup(build) {
    build.onLoad({ filter: /oxc-parser[\\/]src-js[\\/]bindings\.js$/ }, async (a) => ({
      contents: rewrite(await Bun.file(a.path).text(), "@oxc-parser", parserNode, version(parserPkg)),
      loader: "js",
    }));
    build.onLoad({ filter: /oxc-resolver[\\/]index\.js$/ }, async (a) => ({
      contents: rewrite(await Bun.file(a.path).text(), "@oxc-resolver", resolverNode, version(resolverPkg)),
      loader: "js",
    }));
  },
};

// 4. compile the server (+ the scanner's worker, a second entry point inside the same executable)
const serverOut = join(outDir, `rae-server-${triple}${exe}`);
const out = await Bun.build({
  entrypoints: [join(here, "src/server.ts"), join(scanner, "src/workers/extract.worker.ts")],
  compile: { target: target as Bun.Build.CompileTarget, outfile: serverOut },
  minify: true,
  plugins: [embedNative],
});
if (!out.success) {
  for (const l of out.logs) console.error(l);
  throw new Error("server compile failed");
}

// 5. TypeScript 7's native binary + its lib.*.d.ts files (this tsgo build doesn't embed them and
//    panics without them next to the executable) → a resource folder of the app.
const tsPkg = pkgDir(scanner, `@typescript/typescript-${platform.replace(/-(gnu|msvc)$/, "")}`);
const tsgoDir = join(outDir, "tsgo");
rmSync(tsgoDir, { recursive: true, force: true });
mkdirSync(tsgoDir, { recursive: true });
const libFiles = readdirSync(join(tsPkg, "lib")).filter((f) => f.startsWith("lib.") && f.endsWith(".d.ts"));
for (const f of [`tsc${exe}`, ...libFiles]) copyFileSync(join(tsPkg, "lib", f), join(tsgoDir, f));
chmodSync(join(tsgoDir, `tsc${exe}`), 0o755);
rmSync(join(outDir, `rae-tsgo-${triple}${exe}`), { force: true }); // the old layout

console.log(`✔ ${relative(repo, serverOut)}\n✔ ${relative(repo, tsgoDir)}/ (tsc + ${libFiles.length} lib files)`);
