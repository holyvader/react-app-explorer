#!/usr/bin/env bun
/**
 * Local server for the packaged app (the Tauri sidecar): serves the built viewer and the same API as
 * the Vite dev plugin — snapshots, folder browsing, scanning (in-process). Only answers requests from
 * the app itself: loopback Host, same-origin Origin.
 *
 *   rae-server [--port 0] [--snapshots <dir>] [--static <viewer dist dir>] [--log <file>]
 * Prints `RAE_SERVER_URL=http://127.0.0.1:<port>` once listening.
 */
import { appendFileSync, existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, statSync, writeFileSync } from "node:fs";
import { arch, homedir, release, tmpdir } from "node:os";
import { basename, dirname, join, resolve } from "node:path";
import { parseArgs } from "node:util";
import { gitOverview, gitPath, gitRequests, gitTools, isRequestUrl, parseDiffRequest, refreshTools } from "@rae/scanner/git";
import { runScanJob, type ScanEvent } from "@rae/scanner/job";

const { values } = parseArgs({
  options: {
    port: { type: "string", default: "0" },
    snapshots: { type: "string" },
    static: { type: "string" },
    log: { type: "string" },
  },
});

/** Log to stderr and, in the app, to a file the user can send (one previous run kept as .1). */
const logFile = values.log ? resolve(values.log) : undefined;
if (logFile) {
  mkdirSync(dirname(logFile), { recursive: true });
  try {
    if (existsSync(logFile)) renameSync(logFile, `${logFile}.1`);
  } catch {
    /* keep appending */
  }
}
function log(msg: string) {
  const line = `${new Date().toISOString()} ${msg}`;
  console.error(line);
  if (logFile) {
    try {
      appendFileSync(logFile, line + "\n");
    } catch {
      /* logging must never break the server */
    }
  }
}
process.on("uncaughtException", (e) => log(`uncaught: ${e.stack ?? e}`));
process.on("unhandledRejection", (e) => log(`unhandled rejection: ${(e as Error)?.stack ?? e}`));

const snapshotsDir = resolve(values.snapshots ?? join(homedir(), ".react-app-explorer", "snapshots"));
mkdirSync(snapshotsDir, { recursive: true });
/** The viewer's stored settings and diagrams, next to the snapshots folder (the app's data folder). */
const storageFile = join(dirname(snapshotsDir), "viewer-storage.json");
const STORAGE_MAX = 32 * 1024 * 1024;

{
  const tsgo = process.env.RAE_TSGO_PATH;
  log(`start: bun ${Bun.version}, ${process.platform} ${release()} ${arch()}, tmp ${tmpdir()}`);
  log(`snapshots: ${snapshotsDir}`);
  log(`tsgo: ${tsgo ? `${tsgo} (${existsSync(tsgo) ? "found" : "MISSING"}, lib.d.ts ${existsSync(join(dirname(tsgo), "lib.d.ts")) ? "found" : "MISSING"})` : "from the typescript package"}`);
  log(`git: ${gitPath() ?? "not found (diff mode off)"}`);
}

// The viewer: embedded into the executable at build time, or a dist folder (development).
let assets: Record<string, string> = {};
if (values.static) {
  const dir = resolve(values.static);
  const walk = (d: string, prefix = "") => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      if (e.isDirectory()) walk(join(d, e.name), `${prefix}/${e.name}`);
      else assets[`${prefix}/${e.name}`] = join(d, e.name);
    }
  };
  walk(dir);
} else {
  try {
    // @ts-ignore — generated by build.ts (git-ignored); missing when running from source
    assets = (await import("./embedded.generated.ts")).assets;
  } catch {
    console.error("No embedded viewer: run `bun run build` or pass --static <viewer dist>");
  }
}

const SOURCE_FILE = /\.(tsx?|jsx?|mjs|cjs|mts|cts)$/;
const SKIP_DIRS = new Set(["node_modules", ".git", ".next", "dist", "build", "out", "coverage", ".turbo", ".explorer"]);
const LOCAL_HOSTS = new Set(["localhost", "127.0.0.1", "[::1]", "::1"]);

const json = (body: unknown, status = 200) => Response.json(body, { status });

function isTrusted(req: Request): boolean {
  const host = req.headers.get("host") ?? "";
  const hostname = host.startsWith("[") ? host.slice(0, host.indexOf("]") + 1) : host.split(":")[0]!;
  if (!LOCAL_HOSTS.has(hostname)) return false;
  const origin = req.headers.get("origin");
  if (!origin) return true;
  try {
    return new URL(origin).host === host;
  } catch {
    return false;
  }
}

function listIndex() {
  const indexPath = join(snapshotsDir, "index.json");
  if (existsSync(indexPath)) {
    try {
      return JSON.parse(readFileSync(indexPath, "utf8"));
    } catch {
      /* fall back to listing */
    }
  }
  return readdirSync(snapshotsDir)
    .filter((f) => f.endsWith(".json") && f !== "index.json")
    .map((file) => ({ file, createdAt: statSync(join(snapshotsDir, file)).mtime.toISOString() }))
    .sort((a, b) => b.createdAt.localeCompare(a.createdAt));
}

function listDir(path: string) {
  const entries = readdirSync(path, { withFileTypes: true })
    .filter((e) => !e.name.startsWith(".") && !SKIP_DIRS.has(e.name))
    .filter((e) => e.isDirectory() || (e.isFile() && SOURCE_FILE.test(e.name)))
    .map((e) => ({ name: e.name, path: join(path, e.name), kind: e.isDirectory() ? "dir" : "file" }))
    .sort((a, b) => (a.kind === b.kind ? a.name.localeCompare(b.name) : a.kind === "dir" ? -1 : 1));
  const markers = ["package.json", "tsconfig.json", "next.config.js", "next.config.ts", "next.config.mjs"].filter((m) => existsSync(join(path, m)));
  return { path, parent: dirname(path) === path ? null : dirname(path), entries, markers };
}

/** The running scan: its snapshot file (once written) and how to stop it. */
const EDITOR_SCHEMES = new Set(["idea:", "webstorm:", "vscode:", "cursor:"]);

type ScanJob = { file?: string; abort: AbortController };
let scanning: ScanJob | undefined;

/** Deletes snapshot files and their index entries. Returns the files actually removed. */
function deleteSnapshots(files: string[]): string[] {
  const removed: string[] = [];
  for (const f of files) {
    const file = basename(f);
    const full = join(snapshotsDir, file);
    if (!file.endsWith(".json") || file === "index.json" || !existsSync(full)) continue;
    rmSync(full);
    removed.push(file);
  }
  const indexPath = join(snapshotsDir, "index.json");
  if (removed.length && existsSync(indexPath)) {
    try {
      const index = JSON.parse(readFileSync(indexPath, "utf8")) as { file: string }[];
      writeFileSync(indexPath, JSON.stringify(index.filter((e) => !removed.includes(e.file)), null, 2));
    } catch {
      /* a broken index is rebuilt from the folder listing */
    }
  }
  return removed;
}

async function api(req: Request, url: URL): Promise<Response> {
  if (!isTrusted(req)) return json({ error: "Forbidden: the API only serves the local app" }, 403);
  const path = url.pathname;

  if ((path === "/api/snapshots" || path === "/api/snapshots/") && req.method === "DELETE") {
    if (!(req.headers.get("content-type") ?? "").startsWith("application/json")) return json({ error: "Content-Type must be application/json" }, 415);
    let body: { files?: string[] };
    try {
      body = await req.json();
    } catch {
      return json({ error: "Invalid JSON body" }, 400);
    }
    const files = (body.files ?? []).filter((f) => typeof f === "string");
    if (scanning?.file && files.map((f) => basename(f)).includes(scanning.file)) return json({ error: "That snapshot is still being scanned: cancel the scan first" }, 409);
    const removed = deleteSnapshots(files);
    log(`deleted ${removed.length} snapshot(s): ${removed.join(", ")}`);
    return json({ removed });
  }
  if (path === "/api/snapshots" || path === "/api/snapshots/") return json({ dir: snapshotsDir, snapshots: listIndex(), logFile, desktop: true });

  // The viewer's settings and diagrams (its localStorage). The app's server listens on a new port each
  // launch, a new origin for the web view, so its own localStorage would start empty every time.
  if (path === "/api/storage") {
    if (req.method === "GET") {
      try {
        return json({ entries: JSON.parse(readFileSync(storageFile, "utf8")) as Record<string, string> });
      } catch {
        return json({ entries: {} });
      }
    }
    if (req.method !== "PUT") return json({ error: "GET or PUT only" }, 405);
    if (!(req.headers.get("content-type") ?? "").startsWith("application/json")) return json({ error: "Content-Type must be application/json" }, 415);
    let entries: Record<string, unknown>;
    try {
      entries = ((await req.json()) as { entries?: Record<string, unknown> }).entries ?? {};
    } catch {
      return json({ error: "Invalid JSON body" }, 400);
    }
    // the viewer's own keys, string values only
    const kept = Object.fromEntries(Object.entries(entries).filter(([k, v]) => k.startsWith("rae.") && typeof v === "string"));
    const text = JSON.stringify(kept);
    if (text.length > STORAGE_MAX) return json({ error: "Too large" }, 413);
    writeFileSync(`${storageFile}.tmp`, text);
    renameSync(`${storageFile}.tmp`, storageFile);
    return json({ ok: true });
  }

  // Open a file in an editor: the app's web view won't follow other apps' URL schemes, so the OS does.
  if (path === "/api/open") {
    if (req.method !== "POST") return json({ error: "POST only" }, 405);
    if (!(req.headers.get("content-type") ?? "").startsWith("application/json")) return json({ error: "Content-Type must be application/json" }, 415);
    let url: URL;
    try {
      url = new URL(((await req.json()) as { url?: string }).url ?? "");
    } catch {
      return json({ error: "Invalid URL" }, 400);
    }
    // editors, and pull / merge request pages: never hand arbitrary URLs (file:, http:, other apps) to the OS
    if (!EDITOR_SCHEMES.has(url.protocol) && !isRequestUrl(url.href)) return json({ error: `Not an editor or pull / merge request link: ${url.protocol}` }, 400);
    // no control characters or quotes in what goes to the OS (the URL is otherwise percent-encoded)
    // oxlint-disable-next-line no-control-regex -- deliberately matching control characters
    if (/[\u0000-\u001f\u007f"]/.test(url.href)) return json({ error: "Invalid characters in the editor link" }, 400);
    // never through a shell: on Windows `cmd /c start` would treat `&`, `|`… in the URL as commands
    const cmd =
      process.platform === "darwin"
        ? ["open", url.href]
        : process.platform === "win32"
          ? ["rundll32", "url.dll,FileProtocolHandler", url.href]
          : ["xdg-open", url.href];
    const p = Bun.spawnSync(cmd, { stdout: "ignore", stderr: "pipe" });
    if (p.exitCode !== 0) {
      const err = p.stderr.toString().trim() || `exit ${p.exitCode}`;
      log(`open in editor failed: ${url.protocol} ${err}`);
      return json({ error: `Couldn't open the editor: ${err}. Is it installed, and does it handle ${url.protocol}// links?` }, 500);
    }
    return json({ ok: true });
  }
  if (path.startsWith("/api/snapshots/")) {
    const file = basename(decodeURIComponent(path.slice("/api/snapshots/".length)));
    const full = join(snapshotsDir, file);
    if (!file.endsWith(".json") || !existsSync(full)) return json({ error: "not found" }, 404);
    return new Response(Bun.file(full), { headers: { "Content-Type": "application/json" } });
  }

  // git, for diff scans: the repo a folder is in and its branches; open pull / merge requests (network)
  if (path === "/api/git" || path === "/api/git/requests" || path === "/api/git/tools") {
    const q = url.searchParams.get("path");
    if (!q) return json({ error: "path is required" }, 400);
    if (path === "/api/git") return json(await gitOverview(resolve(q)));
    if (path === "/api/git/tools") {
      if (url.searchParams.get("refresh")) refreshTools();
      return json(await gitTools(resolve(q)));
    }
    return json(await gitRequests(resolve(q), (url.searchParams.get("source") ?? "auto") as Parameters<typeof gitRequests>[1]));
  }

  if (path === "/api/fs") {
    const q = url.searchParams.get("path");
    const dir = q ? resolve(q) : homedir();
    try {
      if (!statSync(dir).isDirectory()) return json({ error: `Not a directory: ${dir}` }, 400);
      return json(listDir(dir));
    } catch (e) {
      return json({ error: (e as Error).message }, 404);
    }
  }

  if (path === "/api/scan") {
    if (req.method !== "POST") return json({ error: "POST only" }, 405);
    if (!(req.headers.get("content-type") ?? "").startsWith("application/json")) return json({ error: "Content-Type must be application/json" }, 415);
    if (scanning) return json({ error: "A scan is already running: cancel it first" }, 409);
    let body: { path?: string; types?: boolean; merge?: boolean; diff?: unknown };
    let diff: ReturnType<typeof parseDiffRequest>;
    try {
      body = await req.json();
      diff = parseDiffRequest(body.diff);
    } catch (e) {
      return json({ error: e instanceof SyntaxError ? "Invalid JSON body" : (e as Error).message }, 400);
    }
    const target = body.path ? resolve(body.path) : "";
    if (!target || !existsSync(target)) return json({ error: `Path not found: ${target || "(empty)"}` }, 400);
    const job: ScanJob = { abort: new AbortController() };
    scanning = job;
    // NDJSON stream of ScanEvents: progress, the structure result, then types in the background.
    // Cancelling the request (the page's Cancel button, or the page going away) stops the scan.
    req.signal.addEventListener("abort", () => job.abort.abort());
    let controller: ReadableStreamDefaultController<Uint8Array> | undefined;
    const enc = new TextEncoder();
    const send = (e: ScanEvent) => {
      if (e.type === "result") job.file = e.file;
      if (e.type !== "progress") log(`scan: ${JSON.stringify(e).slice(0, 300)}`);
      try {
        controller?.enqueue(enc.encode(JSON.stringify(e) + "\n"));
      } catch {
        controller = undefined; // the client went away
      }
    };
    const stream = new ReadableStream<Uint8Array>({
      start(c) {
        controller = c;
        void runScanJob(
          target,
          {
            outDir: snapshotsDir,
            types: body.types !== false,
            mergeSingleExport: body.merge !== false,
            diff,
            signal: job.abort.signal,
            onWarn: (m) => log(`warn: ${m}`),
            onProgress: (m) => log(`scan: ${m}`),
          },
          send,
        ).finally(() => {
          scanning = undefined;
          try {
            controller?.close();
          } catch {
            /* already closed */
          }
        });
      },
      cancel() {
        controller = undefined;
        job.abort.abort();
      },
    });
    return new Response(stream, { headers: { "Content-Type": "application/x-ndjson", "Cache-Control": "no-store" } });
  }
  return json({ error: "not found" }, 404);
}

const server = Bun.serve({
  hostname: "127.0.0.1",
  // Scans stream progress, with long quiet stretches (TypeScript loading a big project): no 10s idle cut-off.
  idleTimeout: 0,
  port: Number(values.port),
  async fetch(req) {
    const url = new URL(req.url);
    if (url.pathname.startsWith("/api/")) return api(req, url);
    // the viewer (single-page app): known asset, else index.html
    const file = assets[url.pathname] ?? assets["/index.html"];
    if (file === assets["/index.html"]) console.error(`viewer page served (${url.pathname})`);
    if (!file) return new Response("Viewer not available", { status: 500 });
    return new Response(Bun.file(file));
  },
});

log(`listening on 127.0.0.1:${server.port}`);
console.log(`RAE_SERVER_URL=http://127.0.0.1:${server.port}`);
